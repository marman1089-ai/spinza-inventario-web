const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
const script=fs.readFileSync('app/static/inventory_activity.js','utf8');
let now=0,focused=true,interval,requests=[];const handlers={},windowHandlers={};
const document={visibilityState:'visible',hasFocus:()=>focused,getElementById:()=>({dataset:{store:'spinza',area:'prodotti'}}),addEventListener:(e,fn)=>handlers[e]=fn};
const context={location:{pathname:'/inventario/conteggio'},document,window:{addEventListener:(e,fn)=>windowHandlers[e]=fn},crypto:{randomUUID:()=> '00000000-0000-4000-8000-000000000001'},performance:{now:()=>now},setInterval:fn=>interval=fn,fetch:async(url,options)=>{requests.push(options.body.get('state'));return {status:204}},URLSearchParams};
vm.runInNewContext(script,context);
(async()=>{
 await interval();assert.equal(requests.length,0);
 await handlers.input();assert.deepEqual(requests,['active'],'First interaction must send immediately');
 await interval();assert.equal(requests.length,1,'Throttle repeated activity');
 now=15000;await interval();assert.equal(requests.length,2);
 document.visibilityState='hidden';handlers.visibilitychange();await new Promise(resolve=>setImmediate(resolve));assert.equal(requests.at(-1),'paused');
 document.visibilityState='visible';await interval();assert.equal(requests.length,3,'Need interaction after pause');
 now=30000;await handlers.keydown();assert.equal(requests.at(-1),'active');
 now=45000;focused=false;await interval();assert.equal(requests.length,4);
 now=91000;focused=true;await interval();assert.equal(requests.length,5);assert.equal(requests.at(-1),'paused');
 await handlers.input();assert.equal(requests.length,6);
 await windowHandlers.blur();assert.equal(requests.at(-1),'paused');
 let activated=false;vm.runInNewContext(script,{...context,location:{pathname:'/inventario/report'},setInterval:()=>activated=true});assert.equal(activated,false);
 console.log('PASS: instant entry, throttling, visibility, blur, idle, resume, report exclusion');
})().catch(e=>{console.error(e);process.exitCode=1});
